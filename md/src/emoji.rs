const CATEGORY_ORDER: &[&str] = &["all", "smileys", "people", "animals", "food", "travel", "activities", "objects", "symbols"];

fn category_label(texts: &Texts, key: &str) -> String {
    let label = texts.t(&format!("escritorio.emoji_cat_{}", key));
    if label == format!("escritorio.emoji_cat_{}", key) || label.trim().is_empty() { key.to_owned() } else { label }
}

pub fn run() -> Result<(), Box<dyn std::error::Error>> {
    use std::io::Write;

    let texts = Texts::load();

    let mut present: Vec<&str> = Vec::new();
    for key in CATEGORY_ORDER {
        if *key == "all" || EMOJIS.iter().any(|(_, _, _, c)| *c == *key) { present.push(*key); }
    }

    let categories: Vec<serde_json::Value> = present.iter().map(|key| {
        serde_json::json!({ "key": key, "label": category_label(&texts, key) })
    }).collect();

    let emojis: Vec<serde_json::Value> = EMOJIS.iter().map(|(e, key, fallback, c)| {
        let name = texts.t(key);
        let name = if name == *key || name.trim().is_empty() { (*fallback).to_owned() } else { name };
        serde_json::json!({ "emoji": e, "name": name, "category": c })
    }).collect();

    let data = serde_json::json!({ "categories": categories, "emojis": emojis });

    let data_path = std::env::temp_dir().join(format!("md-emoji-{}.json", std::process::id()));
    let mut f = std::fs::File::create(&data_path)?;
    f.write_all(data.to_string().as_bytes())?;
    f.flush()?;

    let texts = Texts::load();
    let search_prompt = texts.t("escritorio.buscar_emoji");
    let search_prompt = if search_prompt == "escritorio.buscar_emoji" || search_prompt.trim().is_empty() { "Buscar…".to_owned() } else { search_prompt };
    let copied_msg = texts.t("escritorio.emoji_copiado");
    let copied_msg = if copied_msg == "escritorio.emoji_copiado" || copied_msg.trim().is_empty() { "Se copió emoji: {emoji}".to_owned() } else { copied_msg };

    let data_path_s = data_path.to_string_lossy().to_string();
    let envs = vec![("MD_EMOJI_DATA", data_path_s.as_str()), ("MD_EMOJI_SEARCH", search_prompt.as_str()), ("MD_EMOJI_COPIED", copied_msg.as_str()), ("QML_XHR_ALLOW_FILE_READ", "1")];

    let _ = crate::quickshell::spawn_wait("Emoji.qml", &envs);

    let _ = std::fs::remove_file(&data_path);
    Ok(())
}

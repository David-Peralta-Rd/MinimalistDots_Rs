const CATEGORY_ORDER: &[&str] = &["all", "smileys", "people", "animals", "food", "travel", "activities", "objects", "symbols"];

fn localized_names() -> HashMap<String, String> {
    let texts = Texts::load();
    let raw = texts.t("escritorio.emoji_nombres");
    if raw == "escritorio.emoji_nombres" || raw.trim().is_empty() { return HashMap::new(); }
    let mut map = HashMap::new();
    for line in raw.lines() {
        let line = line.trim();
        if line.is_empty() { continue; }
        if let Some((emoji, name)) = line.split_once(char::is_whitespace) {
            let emoji = emoji.trim();
            let name = name.trim();
            if !emoji.is_empty() && !name.is_empty() { map.insert(emoji.to_owned(), name.to_owned()); }
        }
    }
    map
}

fn category_label(texts: &Texts, key: &str) -> String {
    let label = texts.t(&format!("escritorio.emoji_cat_{}", key));
    if label == format!("escritorio.emoji_cat_{}", key) || label.trim().is_empty() { key.to_owned() } else { label }
}

pub fn run() -> Result<(), Box<dyn std::error::Error>> {
    use std::io::Write;

    let texts = Texts::load();
    let names = localized_names();

    // Categorías presentes (en orden fijo) + "all".
    let mut present: Vec<&str> = Vec::new();
    for key in CATEGORY_ORDER {
        if *key == "all" || EMOJIS.iter().any(|(_, _, c)| *c == *key) {
            present.push(*key);
        }
    }

    let categories: Vec<serde_json::Value> = present
        .iter()
        .map(|key| {
            serde_json::json!({
                "key": key,
                "label": category_label(&texts, key),
            })
        })
        .collect();

    let emojis: Vec<serde_json::Value> = EMOJIS
        .iter()
        .map(|(e, fallback, c)| {
            let name = names.get(*e).cloned().unwrap_or_else(|| (*fallback).to_owned());
            serde_json::json!({
                "emoji": e,
                "name": name,
                "category": c,
            })
        })
        .collect();

    let data = serde_json::json!({
        "categories": categories,
        "emojis": emojis,
    });

    // Archivo temporal con los datos para el QML.
    let data_path = std::env::temp_dir().join(format!("md-emoji-{}.json", std::process::id()));
    let mut f = std::fs::File::create(&data_path)?;
    f.write_all(data.to_string().as_bytes())?;
    f.flush()?;

    let texts = Texts::load();
    let search_prompt = texts.t("escritorio.buscar_emoji");
    let search_prompt = if search_prompt == "escritorio.buscar_emoji" || search_prompt.trim().is_empty() {
        "Buscar…".to_owned()
    } else {
        search_prompt
    };
    let copied_msg = texts.t("escritorio.emoji_copiado");
    let copied_msg = if copied_msg == "escritorio.emoji_copiado" || copied_msg.trim().is_empty() {
        "Se copió emoji: {emoji}".to_owned()
    } else {
        copied_msg
    };

    let data_path_s = data_path.to_string_lossy().to_string();
    let envs = vec![
        ("MD_EMOJI_DATA", data_path_s.as_str()),
        ("MD_EMOJI_SEARCH", search_prompt.as_str()),
        ("MD_EMOJI_COPIED", copied_msg.as_str()),
        ("QML_XHR_ALLOW_FILE_READ", "1"),
    ];

    let _ = crate::quickshell::spawn_wait("Emoji.qml", &envs);

    let _ = std::fs::remove_file(&data_path);
    Ok(())
}
